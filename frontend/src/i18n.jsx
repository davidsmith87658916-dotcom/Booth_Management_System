const LanguageContext = createContext({
  lang: 'kh',
  setLang: () => {},
  toggleLang: () => {},
  t: (key, fallback) => fallback || key,
});

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem('expohub_lang');
      if (saved === 'en' || saved === 'kh') return saved;
    } catch {
      // Ignore localStorage errors
    }
    return 'kh'; // Default to Khmer as requested for proper Khmer UX
  });

  const setLang = useCallback((newLang) => {
    const valid = newLang === 'en' ? 'en' : 'kh';
    setLangState(valid);
    try {
      localStorage.setItem('expohub_lang', valid);
    } catch {
      // Ignore localStorage errors
    }
  }, []);

  const toggleLang = useCallback(() => {
    setLangState((prev) => {
      const next = prev === 'en' ? 'kh' : 'en';
      try {
        localStorage.setItem('expohub_lang', next);
      } catch {
        // Ignore localStorage errors
      }
      return next;
    });
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === 'kh' ? 'km' : 'en';
    document.body.dataset.lang = lang;
  }, [lang]);

  const t = useCallback((key, fallbackOrParams, params) => {
    const dict = translations[lang] || translations.en;
    let text = dict[key];
    let actualParams = typeof fallbackOrParams === 'object' ? fallbackOrParams : params;
    let fallback = typeof fallbackOrParams === 'string' ? fallbackOrParams : key;

    if (text === undefined) {
      text = translations.en[key] !== undefined ? translations.en[key] : fallback;
    }

    if (actualParams && typeof actualParams === 'object') {
      Object.entries(actualParams).forEach(([k, v]) => {
        text = text.replaceAll(`{${k}}`, String(v));
      });
    }

    return text;
  }, [lang]);

  return (
    <LanguageContext.Provider value={{ lang, setLang, toggleLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
